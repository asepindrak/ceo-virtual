// Migrate from legacy ~/.realagent if it exists
function checkAndMigrateLegacy() {
  const legacyDir = path.join(os.homedir(), '.realagent');
  if (fs.existsSync(legacyDir) && !fs.existsSync(VIGENT_HOME)) {
    try {
      fs.cpSync(legacyDir, VIGENT_HOME, { recursive: true });
    } catch {
      // ignore
    }
  }
}

// Ensure .gitignore has .vigent/ entry in projects for git clean working tree
export function ensureProjectGitIgnore(projectDir: string) {
  try {
    const gitIgnorePath = path.join(projectDir, '.gitignore');
    const vigentIgnoreEntry = '\n# Vigent internal artifacts & cache\n.vigent/\n';
    if (fs.existsSync(gitIgnorePath)) {
      const content = fs.readFileSync(gitIgnorePath, 'utf-8');
      if (!content.includes('.vigent')) {
        fs.appendFileSync(gitIgnorePath, vigentIgnoreEntry, 'utf-8');
      }
    } else {
      fs.writeFileSync(gitIgnorePath, vigentIgnoreEntry.trim() + '\n', 'utf-8');
    }
  } catch {}
}

// Automatically migrate mixed legacy ~/.vigent/workspaces into separated projects/ and artifacts/
function checkAndMigrateProjectsAndArtifacts() {
  const legacyWorkspaces = path.join(VIGENT_HOME, 'workspaces');
  if (fs.existsSync(legacyWorkspaces) && legacyWorkspaces !== VIGENT_PROJECTS) {
    try {
      const entries = fs.readdirSync(legacyWorkspaces, { withFileTypes: true });
      entries.forEach((entry) => {
        if (!entry.isDirectory()) return;
        const sourcePath = path.join(legacyWorkspaces, entry.name);

        // Task artifacts typically match patterns generated by task titles
        const isTaskArtifact =
          /^(draft-|kembangkan-|integrasi-|implement-|build-|ganti-|create-comprehensive-|task-)/i.test(entry.name);

        const destDir = isTaskArtifact
          ? path.join(VIGENT_ARTIFACTS, 'company-shadowmove', entry.name)
          : path.join(VIGENT_PROJECTS, entry.name);

        const destParent = path.dirname(destDir);
        if (!fs.existsSync(destParent)) {
          fs.mkdirSync(destParent, { recursive: true });
        }

        if (!fs.existsSync(destDir)) {
          fs.cpSync(sourcePath, destDir, { recursive: true });
        }
      });
    } catch (e) {
      console.warn('[Migration Notice]:', e);
    }
  }
}

// Ensure required directories and config exist
export function initRealAgentHomeDirs(): VigentConfig {
  checkAndMigrateLegacy();

  if (!fs.existsSync(VIGENT_HOME)) {
    fs.mkdirSync(VIGENT_HOME, { recursive: true });
  }
  if (!fs.existsSync(VIGENT_PROJECTS)) {
    fs.mkdirSync(VIGENT_PROJECTS, { recursive: true });
  }
  if (!fs.existsSync(VIGENT_ARTIFACTS)) {
    fs.mkdirSync(VIGENT_ARTIFACTS, { recursive: true });
  }
  if (!fs.existsSync(VIGENT_LOGS_DIR)) {
    fs.mkdirSync(VIGENT_LOGS_DIR, { recursive: true });
  }

  // Migrate legacy mixed workspace folders into clean projects and artifacts
  checkAndMigrateProjectsAndArtifacts();

  let config: VigentConfig = {
    port: DEFAULT_PORT,
    autoOpenBrowser: true,
    autorunAtStartup: false,
    workspaceRoot: VIGENT_PROJECTS,
    createdAt: new Date().toISOString(),
  };

  if (!fs.existsSync(VIGENT_CONFIG_FILE)) {
    fs.writeFileSync(VIGENT_CONFIG_FILE, JSON.stringify(config, null, 2), 'utf-8');
  } else {
    try {
      config = { ...config, ...JSON.parse(fs.readFileSync(VIGENT_CONFIG_FILE, 'utf-8')) };
    } catch {
      // Keep default if malformed
    }
  }

  // Auto-scaffold a demo starter project if projects folder is empty
  ensureStarterDemoProject();

  return config;
}

export const initVigentHomeDirs = initRealAgentHomeDirs;

// Update configuration
export function updateRealAgentConfig(updates: Partial<VigentConfig>): VigentConfig {
  const current = initRealAgentHomeDirs();
  const nextConfig = { ...current, ...updates };
  fs.writeFileSync(VIGENT_CONFIG_FILE, JSON.stringify(nextConfig, null, 2), 'utf-8');
  return nextConfig;
}

