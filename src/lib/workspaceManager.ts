export interface ExtractedGitHubInfo {
  url: string;
  owner: string;
  repo: string;
  projectName: string;
}

export interface GitCloneResult {
  success: boolean;
  projectName: string;
  folderPath: string;
  filesCount: number;
  message: string;
  repoUrl: string;
  error?: string;
  isExisting?: boolean;
}

/**
 * Extract GitHub repo information from any text message or raw URL
 */
export function extractGitHubUrl(text: string): ExtractedGitHubInfo | null {
  if (!text) return null;
  const match = text.match(/(?:https?:\/\/(?:www\.)?github\.com\/|git@github\.com:)([a-zA-Z0-9_.-]+)\/([a-zA-Z0-9_.-]+)/i);
  if (!match) return null;
  const owner = match[1];
  let rawRepo = match[2].replace(/[),;!?>]+$/, '');
  let repo = rawRepo.replace(/\.git$/i, '');
  if (repo.endsWith('/')) repo = repo.slice(0, -1);
  if (!owner || !repo) return null;
  const projectName = repo.toLowerCase().replace(/[^a-z0-9_-]/g, '-').replace(/^-+|-+$/g, '') || 'github-repo';
  const cleanUrl = `https://github.com/${owner}/${repo}.git`;
  return {
    url: cleanUrl,
    owner,
    repo,
    projectName,
  };
}

/**
 * Extract simple repository folder name from URL
 */
export function parseRepoNameFromUrl(repoUrl: string): string {
  const extracted = extractGitHubUrl(repoUrl);
  if (extracted) return extracted.projectName;
  const parts = repoUrl.replace(/\.git$/, '').split(/[/:]/);
  return (parts[parts.length - 1] || 'git-repo')
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, '-')
    .replace(/^-+|-+$/g, '') || 'git-repo';
}

/**
 * Clone a Git / GitHub repository directly into ~/.vigent/workspaces
 */
export async function cloneGitRepository(
  repoInput: string,
  targetFolderName?: string
): Promise<GitCloneResult> {
  initRealAgentHomeDirs();

  const extracted = extractGitHubUrl(repoInput);
  let repoUrl = repoInput.trim();
  let folderName = (targetFolderName || '').trim();

  if (extracted) {
    repoUrl = extracted.url;
    if (!folderName) {
      folderName = extracted.projectName;
    }
  } else {
    if (!folderName) {
      folderName = parseRepoNameFromUrl(repoUrl);
    }
  }

  const safeFolderName =
    folderName.toLowerCase().replace(/[^a-z0-9_-]/g, '-').replace(/^-+|-+$/g, '') || 'github-project';
  const targetDir = path.join(VIGENT_PROJECTS, safeFolderName);

  // Check if target directory already exists
  if (fs.existsSync(targetDir)) {
    const gitDir = path.join(targetDir, '.git');
    if (fs.existsSync(gitDir)) {
      // Repository already cloned, run git pull to update
      try {
        await new Promise<void>((resolve) => {
          exec('git pull', { cwd: targetDir, timeout: 60000 }, (error, stdout, stderr) => {
            if (error) {
              console.warn(`[Git Pull Notice]: ${stderr || error.message}`);
            }
            resolve();
          });
        });
        ensureProjectGitIgnore(targetDir);
        const allFiles = getFilesRecursively(targetDir);
        return {
          success: true,
          projectName: safeFolderName,
          folderPath: targetDir,
          filesCount: allFiles.length,
          repoUrl,
          isExisting: true,
          message: `Repositori "${safeFolderName}" sudah ada di folder projects dan berhasil disinkronkan ke versi terbaru.`,
        };
      } catch (err: any) {
        const allFiles = getFilesRecursively(targetDir);
        return {
          success: true,
          projectName: safeFolderName,
          folderPath: targetDir,
          filesCount: allFiles.length,
          repoUrl,
          isExisting: true,
          message: `Repositori "${safeFolderName}" sudah ada di folder projects.`,
        };
      }
    } else {
      // Directory exists but is not git - if non-empty, use unique suffix
      const existingEntries = fs.readdirSync(targetDir);
      if (existingEntries.length > 0) {
        const suffixedName = `${safeFolderName}-${Date.now().toString().slice(-4)}`;
        return cloneGitRepository(repoUrl, suffixedName);
      }
    }
  }

  // Execute git clone
  return new Promise<GitCloneResult>((resolve) => {
    const cloneCmd = `git clone --depth 1 "${repoUrl}" "${targetDir}"`;

    exec(cloneCmd, { timeout: 180000, maxBuffer: 10 * 1024 * 1024 }, (error, stdout, stderr) => {
      if (error) {
        const errorMsg = stderr || error.message || 'Gagal melakukan clone repository';
        resolve({
          success: false,
          projectName: safeFolderName,
          folderPath: targetDir,
          filesCount: 0,
          repoUrl,
          message: `Gagal clone repository: ${errorMsg}`,
          error: errorMsg,
        });
        return;
      }

      ensureProjectGitIgnore(targetDir);
      const allFiles = getFilesRecursively(targetDir);
      resolve({
        success: true,
        projectName: safeFolderName,
        folderPath: targetDir,
        filesCount: allFiles.length,
        repoUrl,
        message: `Berhasil meng-clone repositori "${safeFolderName}" ke folder projects (~/.vigent/projects/${safeFolderName}) dengan ${allFiles.length} file.`,
      });
    });
  });
}


// Open folder in OS File Explorer (Windows explorer / macOS open / Linux xdg-open)
export function openFolderInOS(targetPath?: string) {
  const target = targetPath && fs.existsSync(targetPath) ? targetPath : VIGENT_WORKSPACES;
  if (process.platform === 'win32') {
    exec(`explorer "${target}"`);
  } else if (process.platform === 'darwin') {
    exec(`open "${target}"`);
  } else {
    exec(`xdg-open "${target}"`);
  }
}

// Windows & Cross-platform Autorun at Startup
export function isAutorunConfigured(): boolean {
  if (process.platform === 'win32') {
    try {
      const startupFolder = path.join(
        process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming'),
        'Microsoft',
        'Windows',
        'Start Menu',
        'Programs',
        'Startup'
      );
      const batPath = path.join(startupFolder, 'Vigent.bat');
      const oldBat = path.join(startupFolder, 'RealAgent3D.bat');
      return fs.existsSync(batPath) || fs.existsSync(oldBat);
    } catch {
      return false;
    }
  }
  return false;
}

export function setAutorun(enable: boolean, appPath?: string): boolean {
  const targetAppPath = appPath || process.cwd();
  if (process.platform === 'win32') {
    const startupFolder = path.join(
      process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming'),
      'Microsoft',
      'Windows',
      'Start Menu',
      'Programs',
      'Startup'
    );
    const batPath = path.join(startupFolder, 'Vigent.bat');
    const oldBat = path.join(startupFolder, 'RealAgent3D.bat');

    if (enable) {
      if (!fs.existsSync(startupFolder)) {
        fs.mkdirSync(startupFolder, { recursive: true });
      }
      if (fs.existsSync(oldBat)) {
        try { fs.unlinkSync(oldBat); } catch {}
      }
      const scriptContent = `@echo off\r\ncd /d "${targetAppPath}"\r\nstart /b npm run dev -- -p ${DEFAULT_PORT}\r\n`;
      fs.writeFileSync(batPath, scriptContent, 'utf-8');
      updateRealAgentConfig({ autorunAtStartup: true });
      return true;
    } else {
      if (fs.existsSync(batPath)) fs.unlinkSync(batPath);
      if (fs.existsSync(oldBat)) fs.unlinkSync(oldBat);
      updateRealAgentConfig({ autorunAtStartup: false });
      return false;
    }
  } else if (process.platform === 'darwin') {
    const plistDir = path.join(os.homedir(), 'Library', 'LaunchAgents');
    const plistPath = path.join(plistDir, 'com.vigent.startup.plist');
    if (enable) {
      if (!fs.existsSync(plistDir)) fs.mkdirSync(plistDir, { recursive: true });
      const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.vigent.startup</string>
  <key>ProgramArguments</key>
  <array>
    <string>npm</string>
    <string>run</string>
    <string>dev</string>
    <string>--</string>
    <string>-p</string>
    <string>${DEFAULT_PORT}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${targetAppPath}</string>
  <key>RunAtLoad</key>
  <true/>
</dict>
</plist>`;
      fs.writeFileSync(plistPath, plist, 'utf-8');
      updateRealAgentConfig({ autorunAtStartup: true });
      return true;
    } else {
      if (fs.existsSync(plistPath)) fs.unlinkSync(plistPath);
      updateRealAgentConfig({ autorunAtStartup: false });
      return false;
    }
  } else {
    const autostartDir = path.join(os.homedir(), '.config', 'autostart');
    const desktopPath = path.join(autostartDir, 'vigent.desktop');
    if (enable) {
      if (!fs.existsSync(autostartDir)) fs.mkdirSync(autostartDir, { recursive: true });
      const desktopEntry = `[Desktop Entry]
Type=Application
Exec=npm run dev -- -p ${DEFAULT_PORT}
Path=${targetAppPath}
Hidden=false
NoDisplay=false
X-GNOME-Autostart-enabled=true
Name=Vigent
Comment=Start Vigent Virtual Office Agent on login
`;
      fs.writeFileSync(desktopPath, desktopEntry, 'utf-8');
      updateRealAgentConfig({ autorunAtStartup: true });
      return true;
    } else {
      if (fs.existsSync(desktopPath)) fs.unlinkSync(desktopPath);
      updateRealAgentConfig({ autorunAtStartup: false });
      return false;
    }
  }
}

function getFilesRecursively(dir: string): string[] {
  let results: string[] = [];
  try {
    const list = fs.readdirSync(dir);
    list.forEach((file) => {
      const fullPath = path.join(dir, file);
      const stat = fs.statSync(fullPath);
      if (stat && stat.isDirectory()) {
        if (file !== 'node_modules' && file !== '.git') {
          results = results.concat(getFilesRecursively(fullPath));
        }
      } else {
        results.push(fullPath);
      }
    });
  } catch {
    // ignore unreadable dirs
  }
  return results;
}
