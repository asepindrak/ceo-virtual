const fs = require('fs');
const path = require('path');

async function main() {
  const endpoint = process.env.LLM_ENDPOINT || 'https://api.openai.com/v1/chat/completions';
  const apiKey = process.env.LLM_API_KEY || process.env.OPENAI_API_KEY || '';
  const model = process.env.LLM_MODEL || 'gpt-4o';
  console.log(`Connecting to LLM at ${endpoint} with model ${model}...`);
  
  const prompt = `You are the lead architect at ShadowMove Software House.
Generate a complete, production-ready, beautiful single-page HTML landing page for 'ShadowMove' (a high-performance software house).
Use Tailwind CSS via CDN (<script src="https://cdn.tailwindcss.com"></script>), Google Fonts (Inter and Space Grotesk), and Lucide Icons via CDN (<script src="https://unpkg.com/lucide@latest"></script>).

Requirements:
1. Sleek, premium dark aesthetic (bg-slate-950 and zinc-900 with violet-500, cyan-400, and emerald-400 glow accents).
2. Sticky Header with ShadowMove brand logo (sleek cybernetic SVG or badge), nav links (Services, Projects, Team, Process, Contact), and 'Konsultasi Gratis' CTA button.
3. Hero Section with dynamic glowing badge ('⚡ STEALTH SOFTWARE HOUSE & AUTONOMOUS AI'), impactful headline ('Membangun Ekosistem Digital Berperforma Tinggi di Balik Layar'), engaging subtitle ('ShadowMove merancang aplikasi web sub-detik, sistem AI otonom, dan arsitektur cloud tangguh untuk enterprise dan startup visioner.'), CTA buttons, and interactive code showcase terminal card.
4. Core Services Grid with 6 modern cards with hover micro-animations (Full-Stack Web Engineering, Autonomous AI Agent Workflows, Cloud & DevOps Automation, Mobile App Engineering, UI/UX Design System, Security & Speed Audit).
5. Tech Stack badge showcase (Next.js 15, TypeScript, Python, Docker, PyTorch, Tailwind, Three.js, PostgreSQL).
6. Meet the Team section featuring:
   - Kenji Sato (Founder & System Architect)
   - Rei Kasumi (Senior Creative Frontend Engineer)
   - Damian Vance (Lead Backend & Cloud Engineer)
   - Yuki Tanaka (QA & AI Workflow Automation)
7. Interactive Project Inquiry form with project scope buttons and submit toast message.
8. Footer with live operational badge (● All Systems Operational 99.99%) and office address.
9. Working JavaScript for interactive mobile menu, filter tabs, lucide.createIcons(), and contact form submission with animated toast.

Output ONLY the raw HTML code without markdown code fences or backticks.`;

  const response = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Authorization': apiKey ? `Bearer ${apiKey}` : '',
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      model: model,
      messages: [
        { role: 'system', content: 'You are an elite web architect. Return only clean, valid, complete HTML.' },
        { role: 'user', content: prompt }
      ],
      temperature: 0.7
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`LLM Error [${response.status}]: ${errorText}`);
  }

  const data = await response.json();
  let content = data.choices[0].message.content;
  content = content.replace(/^```html\s*/i, '').replace(/```\s*$/, '').trim();

  // Save to public preview directory for instant browser viewing at /preview/shadowmove/
  const previewDir = path.join(process.cwd(), 'public', 'preview', 'shadowmove');
  fs.mkdirSync(previewDir, { recursive: true });
  fs.writeFileSync(path.join(previewDir, 'index.html'), content, 'utf8');
  console.log('SUCCESS: Written', content.length, 'bytes to', path.join(previewDir, 'index.html'));

  // Also save to user home workspace directory ~/.vigent/workspaces/shadowmove-landing-page/
  const homeDir = process.env.USERPROFILE || process.env.HOME || '';
  if (homeDir) {
    const wsDir = path.join(homeDir, '.vigent', 'workspaces', 'shadowmove-landing-page');
    fs.mkdirSync(wsDir, { recursive: true });
    fs.writeFileSync(path.join(wsDir, 'index.html'), content, 'utf8');
    fs.writeFileSync(path.join(wsDir, 'README.md'), `# ShadowMove Software House - Official Landing Page\n\nGenerated by Vigent Autonomous Multi-Agent Workplace using \`gemini-3.6-flash-medium\` via OpenAI-compatible endpoint.\n`, 'utf8');
    console.log('SUCCESS: Written to user workspace at', wsDir);
  }
}

main().catch(console.error);
